const DICTS: Record<string, Dict> = { 'pt-BR': pt, 'en-US': en, es, ru };

/** Todos os textos do idioma atual — é isto que vai pros webviews. */
export function strings(): Dict {
  return DICTS[config.languageCode()] ?? pt;
}

/** Um texto do idioma atual, com `{variáveis}` preenchidas. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return strings()[key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m));
}
